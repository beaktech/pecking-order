import { readFile, readdir } from 'node:fs/promises'
import { join } from 'node:path'
import { test, expect, searchGreatTits, prepareKeptClip } from './fixtures.js'

test('species picker supports common/scientific names, keyboard selection and Escape', async ({ page, app }) => {
  await page.goto(app.url)
  await expect(page.locator('#archiveStatus')).toContainText('3 clips')
  const input = page.locator('#speciesInput')
  await input.fill('parus major')
  await expect(page.getByRole('listbox', { name: 'Species' }).getByRole('option')).toHaveCount(1)
  await expect(page.getByRole('listbox', { name: 'Species' }).getByRole('option')).toContainText('Great Tit')
  await input.press('ArrowDown')
  await input.press('Enter')
  await expect(input).toHaveValue('Great Tit (Parus major)')
  await expect(input).toHaveAttribute('aria-expanded', 'false')
  await input.fill('Robin')
  await expect(page.getByRole('listbox', { name: 'Species' }).getByRole('option')).toContainText('Erithacus rubecula')
  await input.press('Escape')
  await expect(input).toHaveAttribute('aria-expanded', 'false')
  await input.fill('No such species')
  await expect(page.locator('#speciesMatches')).toHaveText('No matching species.')
})

test('spectrogram seeking works before playback and preserves pause/play state', async ({ page, app }) => {
  await searchGreatTits(page, app)
  const card = page.locator('.recording-card').first()
  const audio = card.locator('audio')
  const slider = card.locator('.spectrogram-player')
  await expect(card.locator('.playhead')).toBeHidden()
  const bounds = await slider.boundingBox()
  await slider.click({ position: { x: bounds.width / 2, y: bounds.height / 2 } })
  await expect.poll(() => audio.evaluate(element => element.currentTime)).toBeCloseTo(3, 0)
  expect(await audio.evaluate(element => element.paused)).toBe(true)
  await slider.press('ArrowRight')
  await expect.poll(() => audio.evaluate(element => element.currentTime)).toBeCloseTo(4, 0)
  await slider.press('Home')
  await card.getByRole('button', { name: 'Play recording', exact: true }).click()
  await expect.poll(() => audio.evaluate(element => element.paused)).toBe(false)
  await expect(card.locator('.playhead')).toBeVisible()
  await slider.click({ position: { x: bounds.width / 4, y: bounds.height / 2 } })
  await expect.poll(() => audio.evaluate(element => element.currentTime)).toBeGreaterThanOrEqual(1.4)
  expect(await audio.evaluate(element => element.paused)).toBe(false)
  await card.getByRole('button', { name: 'Pause recording', exact: true }).click()
  await expect.poll(() => audio.evaluate(element => element.paused)).toBe(true)
  await slider.press('End')
  await expect.poll(() => audio.evaluate(element => element.currentTime)).toBeCloseTo(6, 0)
})

test('keep/reject persist after reload and a failed save leaves the displayed decision unchanged', async ({ page, app }) => {
  await searchGreatTits(page, app)
  let card = page.locator('.recording-card').first()
  const id = await card.getAttribute('data-id')
  await card.getByRole('button', { name: 'Keep', exact: true }).click()
  await expect(card.locator('.kept-badge')).toBeVisible()
  await expect(card.getByRole('button', { name: 'Kept', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.route('**/api/reviews/**', route => route.fulfill({ status: 500, json: { error: 'Synthetic save failure' } }))
  await card.getByRole('button', { name: 'Reject', exact: true }).click()
  await expect(page.locator('#toast')).toHaveText('Synthetic save failure')
  await expect(card.locator('.kept-badge')).toBeVisible()
  await page.unroute('**/api/reviews/**')
  await searchGreatTits(page, app)
  card = page.locator(`[data-id="${id}"]`)
  await expect(card.locator('.kept-badge')).toBeVisible()
  await card.getByRole('button', { name: 'Reject', exact: true }).click()
  await expect(card).toHaveAttribute('data-decision', 'reject')
  await searchGreatTits(page, app)
  await expect(page.locator(`[data-id="${id}"]`)).toHaveAttribute('data-decision', 'reject')
})

test('station drafts survive review-dialog close, preparation reopen and a failed save', async ({ page, app }) => {
  await prepareKeptClip(page, app)
  await page.locator('.preparation-defaults > summary').click()
  const device = page.locator('#upload-device')
  await device.fill('Unsaved recorder')
  await page.getByRole('button', { name: 'Review & confirm', exact: true }).click()
  await page.locator('#closeDialog').click()
  await expect(page.locator('#stationDefaultsForm fieldset')).toBeEnabled()
  await expect(device).toHaveValue('Unsaved recorder')
  await page.locator('#closePreparation').click()
  await page.locator('#exportButton').click()
  await expect(page.locator('#stationDefaultsForm fieldset')).toBeEnabled()
  await expect(device).toHaveValue('Unsaved recorder')
  await page.route('**/api/preparation/defaults', route => route.fulfill({ status: 500, json: { error: 'Synthetic defaults failure' } }))
  await page.getByRole('button', { name: 'Save station details', exact: true }).click()
  await expect(page.locator('#preparationStatus')).toHaveText('Synthetic defaults failure')
  await expect(device).toHaveValue('Unsaved recorder')
  await page.unroute('**/api/preparation/defaults')
  await page.getByRole('button', { name: 'Save station details', exact: true }).click()
  await expect(page.locator('#preparationStatus')).toContainText('Station details saved.')
  await page.reload()
  await page.locator('#exportButton').click()
  await expect(device).toHaveValue('Unsaved recorder')
})

test('upload preparation confirms identification, copies details with fallback and exports a real WAV', async ({ page, app }) => {
  const clip = await prepareKeptClip(page, app)
  await expect(page.locator('#preparationExport')).toBeDisabled()
  await expect(page.locator('#preparationExportNote')).toContainText('will not be exported')
  await page.getByRole('button', { name: 'Review & confirm', exact: true }).click()
  await expect(page.locator('#vocalisationType')).toHaveValue('')
  await page.locator('#vocalisationType').selectOption('call')
  await page.locator('#country').fill('United Kingdom')
  await page.locator('#location').fill('Synthetic garden')
  await page.locator('#latitude').fill('0')
  await page.locator('#longitude').fill('0')
  await page.locator('#confirmed').check()
  await page.getByRole('button', { name: 'Save review', exact: true }).click()
  await expect(page.locator('#reviewDialog')).not.toBeVisible()
  await expect(page.locator('#preparationExport')).toBeEnabled()
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', {
    configurable: true, value: { writeText: async text => { window.copiedDetails = text } },
  }))
  await page.getByRole('button', { name: 'Copy all details', exact: true }).click()
  await expect.poll(() => page.evaluate(() => window.copiedDetails)).toContain('Sound type: call')
  await page.evaluate(() => { navigator.clipboard.writeText = async () => { throw new Error('Clipboard unavailable') } })
  await page.getByRole('button', { name: 'Copy all details', exact: true }).click()
  await expect(page.locator('#preparationCopyText')).toHaveValue(/Location: Synthetic garden/)
  expect(await page.locator('#preparationCopyText').evaluate(element => element.selectionEnd - element.selectionStart)).toBeGreaterThan(0)
  await page.locator('#preparationExport').click()
  await expect(page.locator('#preparationExportResult')).toBeVisible()
  const output = await page.locator('#preparationExportPath').inputValue()
  expect((await readdir(output)).filter(name => name.endsWith('.wav'))).toHaveLength(1)
  expect(await readFile(join(output, 'xeno-canto-metadata.csv'), 'utf8')).toContain('"call"')
  expect(app.store.reviews[clip.id].confirmed).toBe(true)
})
